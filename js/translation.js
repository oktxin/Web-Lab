let currentLanguage = 'ru';

function getTranslation(key) {
    return translations[currentLanguage]?.[key] || translations['ru'][key] || key;
}

function applyTranslation(lang) {
    currentLanguage = lang;
    const elements = document.querySelectorAll('[data-translate]');
    
    elements.forEach(element => {
        const key = element.getAttribute('data-translate');
        if (translations[lang] && translations[lang][key]) {
            if (element.hasAttribute('data-translate-html')) {
                element.innerHTML = translations[lang][key];
            } else if (element.placeholder) {
                element.placeholder = translations[lang][key];
            } else {
                element.textContent = translations[lang][key];
            }
        }
    });

    document.querySelectorAll('.lang-btn').forEach(btn => {
        if (btn.getAttribute('data-lang') === lang) {
            btn.classList.add('active');
        } else {
            btn.classList.remove('active');
        }
    });

    localStorage.setItem('preferredLanguage', lang);
    document.documentElement.lang = lang;

    if (document.querySelector('[data-translate="reviewsPageTitle"]')) {
        document.title = getTranslation('reviewsPageTitle');
    } else if (document.querySelector('[data-translate="favoritesPageTitle"]')) {
        document.title = getTranslation('favoritesPageTitle');
    } else {
        document.title = getTranslation('pageTitle');
    }

    if (typeof updateReviewsTranslation === 'function') {
        updateReviewsTranslation(lang);
    }

    if (typeof updateFavoritesTranslation === 'function') {
        updateFavoritesTranslation(lang);
    }
}

function formatLocalizedDate(dateString, lang) {
    const date = new Date(dateString);
    return date.toLocaleDateString(lang === 'en' ? 'en-US' : 'ru-RU', {
        year: 'numeric',
        month: 'long',
        day: 'numeric'
    });
}

document.addEventListener('DOMContentLoaded', function() {
    const savedLanguage = localStorage.getItem('preferredLanguage');
    const browserLanguage = navigator.language.split('-')[0];
    const langToUse = savedLanguage || (translations[browserLanguage] ? browserLanguage : 'ru');
    
    applyTranslation(langToUse);

    document.querySelectorAll('.lang-btn').forEach(button => {
        button.addEventListener('click', function() {
            const lang = this.getAttribute('data-lang');
            applyTranslation(lang);
        });
    });
});